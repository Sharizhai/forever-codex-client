/** Emplacement que Blizzard n'a pas encore renseigné : visible mais non dépensable */
function createPlaceholderNode(
    category: LegacyCategoryId, index: number, column: number, row: number, requires?: string,
): LegacyTreeNode {
    return {
        id: `${category}-unknown-${index}`,
        category,
        column,
        row,
        icon: null,
        kind: "passive",
        maxRank: 0,
        requires,
        name: () => messages.legacy_node_unknown_name(),
        description: () => messages.legacy_node_unknown_description(),
    };
}

